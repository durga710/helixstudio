/**
 * Bundles the on-disk scaffold templates (templates/<id>/) into a single TS
 * module (src/lib/templates/registry.generated.ts) so they ship inside the
 * serverless deploy — no runtime filesystem reads. Mirrors gen:schema-sql.
 *
 * Run: npm run gen:templates  (also runs at prebuild).
 *
 * Each templates/<id>/ has a template.json manifest plus the starter's source
 * files. template.json is metadata (excluded from the injected files). Only
 * text files are bundled; binaries and node_modules/.git are skipped.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(process.cwd(), "templates");
const OUT = path.resolve(process.cwd(), "src/lib/templates/registry.generated.ts");

const MAX_FILE_CHARS = 48_000; // matches MAX_FILE_CHARS in repo-files.ts
const MAX_FILES_PER_TEMPLATE = 400;
const MAX_TOTAL_CHARS = 1_500_000; // bound the bundle size

const SKIP_DIRS = new Set(["node_modules", ".git", "dist", ".next", "build", "__pycache__", ".venv", "venv"]);
// Text files we bundle. Extensionless dotfiles (.gitignore, .env.example) are allowed explicitly.
const TEXT_EXT = new Set([
  ".html", ".css", ".scss", ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".json", ".jsonc",
  ".md", ".txt", ".py", ".rb", ".go", ".rs", ".java", ".php", ".vue", ".svelte", ".svg",
  ".yml", ".yaml", ".toml", ".ini", ".cfg", ".env", ".sh", ".sql", ".xml",
  // Godot project sources (game-godot template).
  ".gd", ".tscn", ".godot", ".tres", ".import", ".gdshader",
]);
const ALLOW_DOTFILES = new Set([".gitignore", ".env.example", ".npmrc", ".nvmrc", ".editorconfig"]);

function isTextFile(name) {
  if (ALLOW_DOTFILES.has(name)) return true;
  const ext = path.extname(name).toLowerCase();
  return TEXT_EXT.has(ext);
}

function walk(dir, base, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      walk(path.join(dir, entry.name), `${base}${entry.name}/`, out);
    } else if (entry.isFile()) {
      if (entry.name === "template.json") continue; // manifest, not a project file
      const rel = `${base}${entry.name}`;
      if (!isTextFile(entry.name)) {
        console.warn(`[gen-templates] skip non-text file: ${rel}`);
        continue;
      }
      const buf = fs.readFileSync(path.join(dir, entry.name));
      if (buf.includes(0)) {
        console.warn(`[gen-templates] skip binary (NUL): ${rel}`);
        continue;
      }
      const content = buf.toString("utf8").replace(/\r\n/g, "\n");
      if (content.length > MAX_FILE_CHARS) {
        throw new Error(`[gen-templates] ${rel} is ${content.length} chars (> ${MAX_FILE_CHARS}). Trim it.`);
      }
      out.push({ path: rel, content });
    }
  }
}

function main() {
  if (!fs.existsSync(ROOT)) throw new Error(`[gen-templates] no templates/ dir at ${ROOT}`);

  const templates = {};
  let total = 0;
  const ids = fs
    .readdirSync(ROOT, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();

  for (const id of ids) {
    const dir = path.join(ROOT, id);
    const manifestPath = path.join(dir, "template.json");
    if (!fs.existsSync(manifestPath)) {
      console.warn(`[gen-templates] ${id}/ has no template.json — skipping`);
      continue;
    }
    const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
    if (manifest.id !== id) throw new Error(`[gen-templates] ${id}/template.json id="${manifest.id}" must match dir`);

    const files = [];
    walk(dir, "", files);
    files.sort((a, b) => a.path.localeCompare(b.path));
    if (files.length === 0) throw new Error(`[gen-templates] ${id} has no bundlable files`);
    if (files.length > MAX_FILES_PER_TEMPLATE) {
      throw new Error(`[gen-templates] ${id} has ${files.length} files (> ${MAX_FILES_PER_TEMPLATE})`);
    }
    total += files.reduce((n, f) => n + f.content.length, 0);
    templates[id] = { manifest, files };
  }

  if (total > MAX_TOTAL_CHARS) {
    throw new Error(`[gen-templates] templates total ${total} chars (> ${MAX_TOTAL_CHARS}). Trim or remove some.`);
  }

  const header =
    "// AUTO-GENERATED by scripts/gen-templates.mjs — do not edit by hand.\n" +
    "// Run `npm run gen:templates` after changing anything under templates/.\n" +
    'import type { Template } from "./types";\n\n';
  const body =
    "export const TEMPLATES: Record<string, Template> = " +
    JSON.stringify(templates, null, 2) +
    ";\n\nexport const TEMPLATE_IDS: string[] = Object.keys(TEMPLATES);\n";

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, header + body);
  console.log(
    `[gen-templates] wrote ${Object.keys(templates).length} templates ` +
      `(${Object.values(templates).reduce((n, t) => n + t.files.length, 0)} files, ${total} chars) → ${path.relative(process.cwd(), OUT)}`,
  );
}

main();
